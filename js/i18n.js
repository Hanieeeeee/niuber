let lang = localStorage.getItem('rr_lang') || 'zh';

export function getLang() {
  return lang;
}

export function setLang(next) {
  lang = next === 'en' ? 'en' : 'zh';
  localStorage.setItem('rr_lang', lang);
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
  return lang;
}

export function t(key) {
  return dict[lang]?.[key] ?? dict.en[key] ?? key;
}

export function applyStaticI18n() {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });
}

export function labelOf(row, fieldBase) {
  // fieldBase e.g. name → name_zh / name_en
  if (lang === 'zh' && row[`${fieldBase}_zh`]) return row[`${fieldBase}_zh`];
  return row[`${fieldBase}_en`] || row[`${fieldBase}`] || '—';
}
